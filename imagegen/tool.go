package imagegen

import (
	"cmp"
	"context"
	"errors"
	"fmt"
	"strings"
	"uuid"

	"github.com/nostosx/agentx/artifact"
	"github.com/nostosx/agentx/model"
	"github.com/nostosx/agentx/tool"
)

// ToolOptions configures Tool. Request supplies trusted defaults: the model,
// safety identifier and provider options are never chosen by the agent.
type ToolOptions struct {
	Name        string
	Description string
	Request     Request
	// MaxImages limits output images per call; zero defaults to one.
	MaxImages int
	// ResolveImage maps application-owned references to input images, masks
	// and markup. Without it, the tool only offers text-to-image generation.
	// The application owns authorization, URL access and file loading.
	ResolveImage func(context.Context, string) (model.Part, error)
	// Artifacts optionally persists generated bytes. ArtifactScope is trusted
	// application identity, never a model argument. A failure is returned without
	// regenerating images; earlier writes in the same call remain stored.
	Artifacts     artifact.Store
	ArtifactScope string
}

// ArtifactError retains generated output when persistence fails. Applications
// can recover the images and already-saved references without paying for another
// generation. Err retains the storage error's identity through Unwrap.
type ArtifactError struct {
	Response *Response
	Saved    []artifact.Key
	Err      error
}

func (e *ArtifactError) Error() string {
	return fmt.Sprintf("imagegen: artifact persistence failed after generation: %v", e.Err)
}
func (e *ArtifactError) Unwrap() error { return e.Err }

type toolInput struct {
	Prompt       string   `json:"prompt" jsonschema:"Describe the image to generate or the edit to make"`
	N            int      `json:"n,omitempty" jsonschema:"Number of output images"`
	Size         string   `json:"size,omitempty" jsonschema:"Image dimensions, such as 1024x1024, or auto"`
	AspectRatio  string   `json:"aspect_ratio,omitempty" jsonschema:"Provider-supported image aspect ratio, such as 16:9"`
	Quality      string   `json:"quality,omitempty" jsonschema:"Output quality"`
	OutputFormat string   `json:"output_format,omitempty" jsonschema:"Output image format"`
	Background   string   `json:"background,omitempty" jsonschema:"Background mode"`
	Images       []string `json:"images,omitempty" jsonschema:"Application image references to edit"`
	Mask         string   `json:"mask,omitempty" jsonschema:"Application reference of an edit mask"`
	Markup       string   `json:"markup,omitempty" jsonschema:"Application reference of a visual annotation"`
}

// Tool wraps a Generator as a normal Agent tool. When g also implements Editor
// and ResolveImage is configured, the same tool can edit images. It returns
// image parts and response metadata, and is neither read-only nor concurrent
// by default: generating images can incur charges and is not idempotent.
// options can enable the runtime's existing approval and scheduling policies.
func Tool(g Generator, opts ToolOptions, options ...tool.Option) tool.Tool {
	opts.Request.ProviderOptions = model.CloneProviderOptions(opts.Request.ProviderOptions)
	if p := opts.Request.OutputCompression; p != nil {
		v := *p
		opts.Request.OutputCompression = &v
	}
	schema := tool.SchemaOf[toolInput]()
	description := "Generate images from a text prompt."
	if _, ok := g.(Editor); !ok || opts.ResolveImage == nil {
		delete(schema.Properties, "images")
		delete(schema.Properties, "mask")
		delete(schema.Properties, "markup")
	} else {
		description = "Generate images from a prompt, or edit images using application image references."
	}
	minimum, maximum := float64(1), float64(cmp.Or(opts.MaxImages, 1))
	schema.Properties["n"].Minimum, schema.Properties["n"].Maximum = &minimum, &maximum
	options = append([]tool.Option{tool.WithSchema(schema)}, options...)
	return tool.Func(cmp.Or(opts.Name, "generate_image"),
		cmp.Or(opts.Description, description),
		func(ctx context.Context, in toolInput) (*tool.Result, error) {
			return callTool(ctx, g, opts, in)
		}, options...)
}

func callTool(ctx context.Context, g Generator, opts ToolOptions, in toolInput) (*tool.Result, error) {
	if g == nil {
		return nil, errors.New("imagegen: nil generator")
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if strings.TrimSpace(in.Prompt) == "" {
		return nil, errors.New("imagegen: prompt is required")
	}
	if opts.Artifacts != nil && opts.ArtifactScope == "" {
		return nil, errors.New("imagegen: artifact scope is required")
	}
	req := opts.Request
	req.ProviderOptions = model.CloneProviderOptions(req.ProviderOptions)
	req.Prompt = in.Prompt
	req.N = cmp.Or(in.N, req.N, 1)
	req.Size = cmp.Or(in.Size, req.Size)
	req.AspectRatio = cmp.Or(in.AspectRatio, req.AspectRatio)
	req.Quality = cmp.Or(in.Quality, req.Quality)
	req.OutputFormat = cmp.Or(in.OutputFormat, req.OutputFormat)
	req.Background = cmp.Or(in.Background, req.Background)
	limit := cmp.Or(opts.MaxImages, 1)
	if req.N < 1 || limit < 1 || req.N > limit {
		return nil, fmt.Errorf("imagegen: output count must be between 1 and %d", limit)
	}
	var resp *Response
	var err error
	if len(in.Images) == 0 {
		if in.Mask != "" || in.Markup != "" {
			return nil, errors.New("imagegen: a mask or markup requires input images")
		}
		resp, err = g.Generate(ctx, &req)
	} else {
		e, ok := g.(Editor)
		if !ok || opts.ResolveImage == nil {
			return nil, errors.New("imagegen: image editing is not configured")
		}
		edit := EditRequest{Request: req}
		for _, ref := range in.Images {
			p, resolveErr := opts.ResolveImage(ctx, ref)
			if resolveErr != nil {
				return nil, fmt.Errorf("imagegen: resolve image: %w", resolveErr)
			}
			edit.Images = append(edit.Images, p)
		}
		for _, input := range []struct {
			ref    string
			target **model.Part
		}{{in.Mask, &edit.Mask}, {in.Markup, &edit.Markup}} {
			if input.ref == "" {
				continue
			}
			p, resolveErr := opts.ResolveImage(ctx, input.ref)
			if resolveErr != nil {
				return nil, fmt.Errorf("imagegen: resolve edit reference: %w", resolveErr)
			}
			*input.target = &p
		}
		resp, err = e.Edit(ctx, &edit)
	}
	if err != nil {
		return nil, err
	}
	if resp == nil || len(resp.Images) == 0 {
		return nil, errors.New("imagegen: provider returned no images")
	}
	parts := make([]model.Part, len(resp.Images))
	var saved []artifact.Key
	for i, img := range resp.Images {
		if img.Part.Type != model.PartImage || len(img.Part.Data) == 0 && img.Part.URL == "" && img.Part.FileID == "" {
			return nil, errors.New("imagegen: provider returned an empty image")
		}
		parts[i] = img.Part
		if opts.Artifacts != nil {
			if len(img.Part.Data) == 0 {
				return nil, &ArtifactError{Response: resp, Saved: saved, Err: errors.New("artifact persistence requires inline image bytes")}
			}
			value := &artifact.Artifact{Scope: opts.ArtifactScope, ID: uuid.New().String(),
				MediaType: img.Part.MediaType, Data: img.Part.Data,
				Metadata: map[string]string{"provider": resp.Provider, "model": resp.Model, "request_id": resp.RequestID}}
			if err := opts.Artifacts.Put(ctx, value); err != nil {
				return nil, &ArtifactError{Response: resp, Saved: saved, Err: err}
			}
			saved = append(saved, value.Key)
		}
	}
	out := tool.Media(fmt.Sprintf("Generated %d image(s).", len(parts)), parts...)
	// Keep binary data in Parts only; metadata remains small and serializable.
	out.Metadata = map[string]any{"provider": resp.Provider, "model": resp.Model,
		"request_id": resp.RequestID, "usage": resp.Usage, "size": resp.Size,
		"quality": resp.Quality, "background": resp.Background, "output_format": resp.OutputFormat}
	if len(saved) > 0 {
		out.Metadata["artifacts"] = saved
	}
	return out, nil
}
